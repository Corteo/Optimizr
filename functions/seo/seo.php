// Filtre pour personnaliser le robots.txt
add_filter('robots_txt', function ($output, $public) {
    if (!get_option('haptic_enable_robots')) {
        return $output;
    }

    $custom = get_option('haptic_custom_robots_txt', '');
    return !empty($custom) ? $custom : $output;
}, 10, 2);


// Multisite : jamais d'écriture, la racine est commune à tous les sites du réseau
add_action('admin_post_haptic_generate_robots_txt', function () {
    if (!current_user_can('manage_options') || is_multisite()) {
        wp_die(esc_html__('Access denied', 'optimizr'));
    }
    check_admin_referer('haptic_generate_robots_txt');

    $content = (string) get_option('haptic_custom_robots_txt', '');
    $file = ABSPATH . 'robots.txt';

    if (trim($content) === '') {
        $message = 'robots_empty';
    } elseif (@file_put_contents($file, $content) === strlen($content)) {
        // Empreinte du contenu écrit : le fichier n'est supprimé à la désactivation que s'il n'a pas été modifié depuis
        update_option('haptic_robots_txt_hash', md5($content), false);
        $message = 'robots_generated';
    } else {
        $message = 'robots_failed';
    }

    haptic_seo_http_check_reset('robots');
    wp_safe_redirect(add_query_arg('haptic_message', $message, haptic_admin_tab_url('seo')));
    exit;
});

add_action('admin_post_haptic_delete_robots_txt', function () {
    if (!current_user_can(is_multisite() ? 'manage_network_options' : 'manage_options')) {
        wp_die(esc_html__('Access denied', 'optimizr'));
    }
    check_admin_referer('haptic_delete_robots_txt');

    $file = ABSPATH . 'robots.txt';
    if (file_exists($file)) {
        wp_delete_file($file);
    }
    $ok = !file_exists($file);
    if ($ok) {
        delete_option('haptic_robots_txt_hash');
    }

    haptic_seo_http_check_reset('robots');
    wp_safe_redirect(add_query_arg('haptic_message', $ok ? 'robots_deleted' : 'robots_delete_failed', haptic_admin_tab_url('seo')));
    exit;
});
