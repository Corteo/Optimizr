add_action('admin_post_haptic_generate_sitemap_now', function () {
    if (!current_user_can('manage_options')) {
        wp_die(esc_html__('Access denied', 'optimizr'));
    }
    check_admin_referer('haptic_generate_sitemap_now');
    $ok = haptic_write_sitemap_to_file(_x('manual', 'sitemap generation trigger', 'optimizr'));
    flush_rewrite_rules();
    wp_safe_redirect(add_query_arg('haptic_message', $ok ? 'sitemap_regenerated' : 'sitemap_failed', haptic_admin_tab_url('seo')));
    exit;
});

function haptic_show_sitemap_notice()
{
    if (!isset($_GET['haptic_message'])) {
        return;
    }

    $messages = [
        'sitemap_regenerated' => __('The sitemap has been regenerated.', 'optimizr'),
        'robots_generated'    => __('The robots.txt file was generated successfully.', 'optimizr'),
        'robots_deleted'      => __('The robots.txt file has been deleted: robots.txt is generated by WordPress again.', 'optimizr'),
    ];
    $errors = [
        'robots_empty'         => __('Save the robots.txt content first.', 'optimizr'),
        'robots_failed'        => __('Unable to write the robots.txt file. Check the write permissions of the site root folder.', 'optimizr'),
        'robots_delete_failed' => __('Unable to delete the robots.txt file. Check the write permissions of the site root folder.', 'optimizr'),
    ];

    $key = sanitize_key($_GET['haptic_message']);
    if ($key === 'sitemap_failed') {
        echo '<div class="notice notice-error is-dismissible"><p>' . esc_html(get_option('haptic_sitemap_error', __('Sitemap generation failed.', 'optimizr'))) . '</p></div>';
    } elseif (isset($errors[$key])) {
        echo '<div class="notice notice-error is-dismissible"><p>' . esc_html($errors[$key]) . '</p></div>';
    } elseif (isset($messages[$key])) {
        echo '<div class="notice notice-success is-dismissible"><p>' . esc_html($messages[$key]) . '</p></div>';
    }
}
add_action('admin_notices', 'haptic_show_sitemap_notice');

