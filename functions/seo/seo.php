// Callback pour l'état et la régénération du sitemap
function haptic_generate_sitemap_button_callback()
{
    $url = wp_nonce_url(admin_url('admin-post.php?action=haptic_generate_sitemap_now'), 'haptic_generate_sitemap_now');
    $error = get_option('haptic_sitemap_error');
    $history = (array) get_option('haptic_sitemap_history', []);
    $file_exists = haptic_sitemap_is_published();
    $file_url = home_url('/sitemap.xml');

    // Vérifie l'accessibilité HTTP
    $http_ok = $file_exists && haptic_seo_http_check('sitemap', $file_url, 'HEAD') === 200;

    $details = '';
    if (!empty($history[0])) {
        /* translators: %d: number of URLs in the sitemap */
        $urls = sprintf(_n('%d URL', '%d URLs', $history[0]['count'], 'optimizr'), $history[0]['count']);
        /* translators: date format for the last sitemap generation, see https://www.php.net/manual/datetime.format.php */
        $date = mysql2date(__('F j, Y \a\t g:i a', 'optimizr'), $history[0]['time']);
        /* translators: 1: number of URLs, 2: date of the last generation */
        $details = ' · ' . sprintf(__('%1$s · last generated: %2$s', 'optimizr'), $urls, $date);
    }

    if ($error) {
        echo '<div class="optimizr-notice optimizr-notice--warn">' . wp_kses(haptic_icon('alert', 18), haptic_kses_ui()) . '<span><strong>' . esc_html__('The last generation failed.', 'optimizr') . '</strong> ' . esc_html($error) . '</span></div>';
    } elseif (!$file_exists) {
        echo '<div class="optimizr-notice optimizr-notice--warn">' . wp_kses(haptic_icon('alert', 18), haptic_kses_ui()) . '<span><strong>' . esc_html__('The sitemap.xml file is missing.', 'optimizr') . '</strong> ' . esc_html__('Regenerate it below.', 'optimizr') . '</span></div>';
    } elseif (!$http_ok) {
        echo '<div class="optimizr-notice optimizr-notice--warn">' . wp_kses(haptic_icon('alert', 18), haptic_kses_ui()) . '<span><strong>' . esc_html__('sitemap.xml exists but does not respond over HTTP', 'optimizr') . '</strong>' . esc_html($details) . '</span><a href="' . esc_url($file_url) . '" target="_blank" rel="noopener">' . esc_html__('Open', 'optimizr') . '</a></div>';
    } else {
        echo '<div class="optimizr-notice optimizr-notice--ok">' . wp_kses(haptic_icon('check', 18), haptic_kses_ui()) . '<span><strong>' . esc_html__('sitemap.xml is reachable', 'optimizr') . '</strong>' . esc_html($details) . '</span><a href="' . esc_url($file_url) . '" target="_blank" rel="noopener">' . esc_html__('Open', 'optimizr') . '</a></div>';
    }

    echo '<div class="optimizr-inline">';
    echo '<a href="' . esc_url($url) . '" class="optimizr-btn optimizr-btn--secondary">' . wp_kses(haptic_icon('refresh', 16), haptic_kses_ui()) . esc_html__('Regenerate now', 'optimizr') . '</a>';
    echo '</div>';

    if ($history) {
        echo '<details class="optimizr-details"><summary>' . esc_html__('Generation history', 'optimizr') . '</summary><ul>';
        foreach ($history as $entry) {
            printf(
                '<li>%s · %s · %s</li>',
                /* translators: date format for the sitemap generation history, see https://www.php.net/manual/datetime.format.php */
                esc_html(mysql2date(__('M j, Y, g:i a', 'optimizr'), $entry['time'])),
                esc_html($entry['origin']),
                /* translators: %d: number of URLs in the sitemap */
                $entry['ok'] ? esc_html(sprintf(_n('%d URL', '%d URLs', $entry['count'], 'optimizr'), $entry['count'])) : '<strong>' . esc_html__('write failed', 'optimizr') . '</strong>'
            );
        }
        echo '</ul></details>';
    }

    /* translators: %s: shortcode */
    echo '<p class="optimizr-field__help">' . wp_kses_post(sprintf(esc_html__('Sitemap for visitors: place the %s shortcode in a page.', 'optimizr'), '<code>[optimizr_plan_du_site]</code>')) . '</p>';
}

