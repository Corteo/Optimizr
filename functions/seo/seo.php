function haptic_custom_robots_txt_callback()
{
    $db_value = get_option('haptic_custom_robots_txt', '');
    $file_path = ABSPATH . 'robots.txt';
    $file_exists = file_exists($file_path);

    // Fichier physique : le serveur l'envoie sans passer par WordPress, ce réglage est ignoré
    if ($file_exists) {
        echo '<div class="optimizr-notice optimizr-notice--warn">' . wp_kses(haptic_icon('alert', 18), haptic_kses_ui()) . '<span><strong>' . esc_html__('A robots.txt file exists at the site root: it is served instead of this setting.', 'optimizr') . '</strong> ';
        if (is_multisite()) {
            echo esc_html__('It is shared by all sites in the network.', 'optimizr');
        } elseif (haptic_robots_txt_is_ours()) {
            echo esc_html__('Written by Optimizr, it is deleted when the plugin is deactivated.', 'optimizr');
        } else {
            echo esc_html__('It was not written by Optimizr, or has been modified since.', 'optimizr');
        }
        echo '</span>';
        if (current_user_can(is_multisite() ? 'manage_network_options' : 'manage_options')) {
            echo '<a href="' . esc_url(wp_nonce_url(admin_url('admin-post.php?action=haptic_delete_robots_txt'), 'haptic_delete_robots_txt')) . '" onclick="return confirm(' . esc_attr(wp_json_encode(__('Delete the robots.txt file from the site root?', 'optimizr'))) . ');">' . esc_html__('Delete the file', 'optimizr') . '</a>';
        }
        echo '</div>';
    }

    // La valeur enregistrée prime ; le fichier existant ne sert qu'à pré-remplir le champ
    if (!empty($db_value)) {
        $value = $db_value;
    } elseif ($file_exists) {
        $value = file_get_contents($file_path);
    } else {
        $value = "User-agent: *\nDisallow:\nSitemap: " . home_url('/sitemap.xml');
    }

    echo '<textarea name="haptic_custom_robots_txt" rows="8" class="optimizr-code" id="haptic_custom_robots_txt_field" spellcheck="false">' . esc_textarea($value) . '</textarea>';

    echo '<div class="optimizr-inline">';

    // Test d'accessibilité du robots.txt, seulement quand ce réglage s'applique
    $robots_url = home_url('/robots.txt');
    if (!get_option('haptic_enable_robots')) {
        echo '<span class="optimizr-status optimizr-status--off">' . esc_html__('Customization disabled', 'optimizr') . '</span>';
    } else {
        $code = haptic_seo_http_check('robots', $robots_url);
        if ($code === 0) {
            echo '<span class="optimizr-status optimizr-status--warn">' . esc_html__('Unreachable', 'optimizr') . '</span>';
        } elseif ($code === 200) {
            echo '<a href="' . esc_url($robots_url) . '" target="_blank" rel="noopener" class="optimizr-status optimizr-status--ok">' . esc_html__('Reachable (HTTP 200)', 'optimizr') . '</a>';
        } else {
            /* translators: %d: HTTP status code */
            echo '<span class="optimizr-status optimizr-status--warn">' . esc_html(sprintf(__('HTTP response %d', 'optimizr'), $code)) . '</span>';
        }
    }

    // Multisite : la racine est commune à tous les sites du réseau
    if (!is_multisite()) {
        echo '<a href="' . esc_url(wp_nonce_url(admin_url('admin-post.php?action=haptic_generate_robots_txt'), 'haptic_generate_robots_txt')) . '" class="optimizr-btn optimizr-btn--secondary optimizr-push">' . esc_html__('Write the robots.txt file', 'optimizr') . '</a>';
    }
    echo '</div>';

    echo '<details class="optimizr-details"><summary>' . esc_html__('Example directives', 'optimizr') . '</summary><ul>';
    /* translators: %s: robots.txt directive */
    echo '<li>' . wp_kses_post(sprintf(esc_html__('%s applies to all robots', 'optimizr'), '<code>User-agent: *</code>')) . '</li>';
    /* translators: %s: robots.txt directive */
    echo '<li>' . wp_kses_post(sprintf(esc_html__('%s blocks access to the admin', 'optimizr'), '<code>Disallow: /wp-admin/</code>')) . '</li>';
    /* translators: %s: robots.txt directive */
    echo '<li>' . wp_kses_post(sprintf(esc_html__('%s allows a subfolder', 'optimizr'), '<code>Allow: /wp-content/uploads/</code>')) . '</li>';
    /* translators: %s: robots.txt directive */
    echo '<li>' . wp_kses_post(sprintf(esc_html__('%s points to the sitemap', 'optimizr'), '<code>Sitemap: ' . esc_html(home_url('/sitemap.xml')) . '</code>')) . '</li>';
    echo '</ul></details>';
}

